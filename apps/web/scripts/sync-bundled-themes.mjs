import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { access, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  assertRuntimeThemeArchiveEntries,
  collectRuntimeThemeSourceFiles,
  readZipArchiveEntries
} from './bundled-theme-runtime.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '../../..');
const outputDir = path.join(projectRoot, 'static/cdn/themes');
const generatedModulePath = path.join(
  projectRoot,
  'apps/web/src/features/viewer/bundled-themes.generated.ts'
);

// Every bundled theme ships from the same `themes/resume` submodule. The public
// archive intentionally contains only runtime Python/templates/fonts from the
// five theme packages plus their shared font directory. Resume data, variants,
// fixtures, tests, build tooling and repository metadata must never be shipped.
// A single shared archive avoids emitting five byte-identical runtime bundles.
const submodulePath = path.join(projectRoot, 'themes/resume');
const sharedArchiveBaseName = 'bundled-resume-themes';

const THEME_SOURCES = [
  {
    design: 'design:\n  theme: ahmadstyle\n',
    packageDir: 'ahmadstyle',
    themeKey: 'ahmadstyle'
  },
  {
    design: 'design:\n  theme: phdjakes\n',
    packageDir: 'phdjakes',
    themeKey: 'phdjakes'
  },
  {
    design: 'design:\n  theme: phddeedy\n',
    packageDir: 'phddeedy',
    themeKey: 'phddeedy'
  },
  {
    design: 'design:\n  theme: phdresearch\n',
    packageDir: 'phdresearch',
    themeKey: 'phdresearch'
  },
  {
    design: 'design:\n  theme: tylerstyle\n',
    packageDir: 'tylerstyle',
    themeKey: 'tylerstyle'
  }
];

async function assertThemeSourceReady(themeSource) {
  const packageRoot = path.join(submodulePath, themeSource.packageDir);
  const requiredFiles = [
    path.join(packageRoot, '__init__.py'),
    path.join(packageRoot, 'Preamble.j2.typ')
  ];

  try {
    await Promise.all(requiredFiles.map((filePath) => access(filePath)));
  } catch {
    throw new Error(
      `Theme source is incomplete at ${submodulePath}. ` +
        `Expected ${themeSource.packageDir}/__init__.py and theme templates. ` +
        'Make sure the submodule is checked out before running the bundle sync.'
    );
  }
}

function createRuntimeZip(submodulePath, runtimeFiles) {
  const archiveBuffer = execFileSync('zip', ['-q', '-X', '-', '-@'], {
    cwd: submodulePath,
    input: `${runtimeFiles.join('\n')}\n`,
    maxBuffer: 50 * 1024 * 1024
  });
  return Buffer.from(archiveBuffer);
}

async function writeFileIfChanged(filePath, content) {
  const next = typeof content === 'string' ? content : Buffer.from(content);

  try {
    const current = await readFile(filePath);
    const currentBuffer = Buffer.isBuffer(next) ? current : current.toString('utf8');

    if (Buffer.isBuffer(next) ? current.equals(next) : currentBuffer === next) {
      return;
    }
  } catch {
    // Fall through and create the file.
  }

  await writeFile(filePath, next);
}

// Build the single shared archive every theme references. Returns its name and
// public path; callers attach the per-theme `design`/`themeKey` metadata.
async function syncSharedArchive() {
  await mkdir(outputDir, { recursive: true });

  for (const themeSource of THEME_SOURCES) {
    await assertThemeSourceReady(themeSource);
  }

  const runtimeFiles = await collectRuntimeThemeSourceFiles(submodulePath);
  const archiveBytes = createRuntimeZip(submodulePath, runtimeFiles);
  const hash = createHash('sha256').update(archiveBytes).digest('hex').slice(0, 12);
  const archiveName = `${sharedArchiveBaseName}-${hash}.zip`;
  const archivePath = path.join(outputDir, archiveName);

  // Remove every other archive in the output dir, which also clears the legacy
  // per-theme zips (ahzs645-resume-*, phd-*-*) from before the dedupe.
  for (const entry of await readdir(outputDir)) {
    if (entry.endsWith('.zip') && entry !== archiveName) {
      await rm(path.join(outputDir, entry), { force: true });
    }
  }

  await writeFileIfChanged(archivePath, archiveBytes);
  assertRuntimeThemeArchiveEntries(readZipArchiveEntries(archivePath), archiveName);

  return {
    archiveName,
    archivePath: `cdn/themes/${archiveName}`
  };
}

function createGeneratedModule(themes) {
  return `// Auto-generated by apps/web/scripts/sync-bundled-themes.mjs\nexport type BundledTheme = {\n  archiveName: string;\n  archivePath: string;\n  design: string;\n  themeKey: string;\n};\n\nexport const BUNDLED_THEMES: BundledTheme[] = ${JSON.stringify(themes, null, 2)};\n`;
}

function readManifestArchivePaths(source) {
  return [...source.matchAll(/"archivePath":\s*"([^"]+)"/g)].map((match) => match[1]);
}

// The committed manifest is only safe to reuse if every archive it references
// is actually present on disk. Otherwise a build with a missing submodule would
// ship a manifest pointing at theme zips that were never generated, which fails
// silently at runtime with "custom theme folder ... does not exist".
async function existingManifestIsUsable() {
  let source;
  try {
    source = await readFile(generatedModulePath, 'utf8');
  } catch {
    return false;
  }

  const archivePaths = readManifestArchivePaths(source);
  if (archivePaths.length === 0) {
    return false;
  }

  for (const archivePath of archivePaths) {
    try {
      const absolutePath = path.join(projectRoot, 'static', archivePath);
      await access(absolutePath);
      assertRuntimeThemeArchiveEntries(
        readZipArchiveEntries(absolutePath),
        `fallback ${archivePath}`
      );
    } catch {
      return false;
    }
  }

  return true;
}

async function main() {
  try {
    const sharedArchive = await syncSharedArchive();

    const themes = THEME_SOURCES.map((themeSource) => ({
      archiveName: sharedArchive.archiveName,
      archivePath: sharedArchive.archivePath,
      design: themeSource.design,
      themeKey: themeSource.themeKey
    }));

    await writeFileIfChanged(generatedModulePath, createGeneratedModule(themes));
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);

    if (await existingManifestIsUsable()) {
      console.warn('[bundled-themes] Falling back to the existing generated manifest.', message);
      return;
    }

    throw new Error(
      '[bundled-themes] Could not generate the bundled theme archives and no usable ' +
        'manifest exists on disk. The build would ship without working themes. Check out the ' +
        "'themes/resume' submodule first: git submodule update --init --recursive\n" +
        `Cause: ${message}`
    );
  }
}

await main();
